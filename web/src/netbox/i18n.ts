const pick = (d: Dict, key: string, lang: Lang) => d[key]?.[lang === 'ru' ? 1 : 0];

export const humanize = (s: string) => {
  const t = s.replace(/^_/, '').replace(/_/g, ' ');
  return t.charAt(0).toUpperCase() + t.slice(1);
};

/** UI string with `{var}` interpolation. */
export function t(key: string, vars: Record<string, string | number> = {}, lang: Lang = currentLang()): string {
  const s = pick(ui, key, lang) ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? `{${k}}`));
}

export const typeLabel = (path: string, fallback?: string, lang: Lang = currentLang()) => pick(types, path, lang) ?? fallback ?? humanize(path);
export const fieldLabel = (name: string, lang: Lang = currentLang()) => pick(fields, name, lang) ?? humanize(name.replace(/_id$/, ''));
/** Translates a choice value; falls back to the server label. */
export const valueLabel = (value: string, serverLabel?: string, lang: Lang = currentLang()) =>
  lang === 'ru' ? (pick(values, value, lang) ?? serverLabel ?? value) : (serverLabel ?? pick(values, value, lang) ?? value);

